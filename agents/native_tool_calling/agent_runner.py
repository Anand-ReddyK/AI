"""
Orchestrator Loop:
- Handles parallel tool calls in a single turn.
- Strictly adheres to the OpenAI/Groq message ordering protocol.
- Feeds tool observations and runtime errors back to the model.
- Halts when a final answer is returned or max_turns is reached.
"""

import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from groq import Groq

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from agents.native_tool_calling.sample_tools import registry

load_dotenv()
GROQ_API_KEY = os.getenv("GROQ_API_KEY")

if not GROQ_API_KEY:
    raise ValueError("GROQ_API_KEY environment variable is not set.")

client = Groq(api_key=GROQ_API_KEY)
MODEL = "qwen/qwen3.8-27b"

def run_agent(user_query: str, max_turns: int = 6) -> str:
    """
    Executes a multi-turn agent loop:
    - Passes registered tool schemas to Groq.
    - Inspects if the assistant returned content or tool_calls.
    - Iterates and executes all tool calls (supporting parallel calls).
    - Appends tool observations back to message history.
    - Exits when the assistant produces a final answer.
    """
    system_prompt = (
        "You are a helpful, precise assistant with access to real-time tools\n"
        "1. Always use tools when real-time data or calculations are required.\n"
        "2. If multiple pieces of information are needed, you can call multiple tools in parallel.\n"
        "3. If a tool returns an error, read the error message carefully and adapt your approuch.\n"
        "4. Once you have sufficient information, provide a clear, concise final answer.\n"
        "5. Never mix tool calls with final answers in the same response."
        "6. In case of inconsistancy in tool callings (ex. arguments behave different from description, etc), or unable to get the answer from the provided tools, you should inform the user about it."
    )

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_query}
    ]

    # Fetch OpenAI/Groq compatable schemas generated by Pydantic
    tools_schema = registry.get_tool_schemas()

    print("=" * 70)
    print(f"[User prompt]: {user_query}")
    print("=" * 70)

    for turn in range(1, max_turns + 1):
        print(f"\n-----> [Turn {turn}/{max_turns}] Requesting LLM response...")

        response = client.chat.completions.create(
            model=MODEL,
            messages=messages,
            tools=tools_schema,
            tool_choice="auto",
            temperature=0.0
        )

        choice = response.choices[0]
        assistant_message = choice.message

        #* Always append the assistant message to history before adding tool replies
        messages.append(assistant_message)

        print(f"[Reasoning]: {assistant_message.reasoning}\n")
        
        # Case A: Model requests too calls
        if assistant_message.tool_calls:
            num_calls = len(assistant_message.tool_calls)
            print(f"[*] Assistant requests {num_calls} tool call(s)")

            # Execute and provide an observation for EVERY tool_call in this turn
            for idx, tool_call in enumerate(assistant_message.tool_calls, start=1):
                call_id = tool_call.id
                func_name = tool_call.function.name
                func_args = tool_call.function.arguments

                print(f"    [{idx}/{num_calls}] Executing {func_name}({func_args}) ...")

                # Safe execution with Pydantic validation & exception capture
                observation = registry.execute_tool(func_name, func_args)
                print(f"        --- Observation: {observation}")

                # Add a message with role = "tool" matching the tool_call_id
                messages.append({
                    "role": "tool",
                    "tool_call_id": call_id,
                    "content": observation
                })
            
            # Continue so the model can inspect the observations and decide on the next step.
            continue

        if assistant_message.content:
            print(f"\n[Final Answer]: \n{assistant_message.content}\n{"=" * 70}")
            return assistant_message.content
    
    print("\n<!> Max turns reached without a final answer.\n")
    return "Error: Maximum turns exceeded."


